i = 0
while i < n:
    k += 1
    i += 1


# Цикл виконується n разів, оскільки на кожній ітерації
# змінна i збільшується на 1.
# Відповідь: O(n).


# b)
i = 1
while i < n:
    i = i * 2


# На кожній ітерації значення i подвоюється.
# Кількість ітерацій пропорційна log2(n).
# Відповідь: O(log n).


# c)
i = 0
while i < n:
    if i % 2 == 0:
        k += 1
    i += 1


# Цикл виконується n разів. Перевірка парності
# та виконання умовного оператора займають сталий час.
# Відповідь: O(n).


# d)
i = 0
while i < n:
    j = i
    while j < n:
        k += 1
        j += 1
    i += 1

# На кожному кроці зовнішнього циклу j починається з i.
# Через це внутрішній цикл з кожним разом
# виконується на одну ітерацію менше.
# У сумі кількість операцій має квадратичну залежність.
# Складність: O(n^2).




